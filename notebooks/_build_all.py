            "                                     enumerate_original_objective,\n"
            "                                     find_optima, validate_qubo_vs_original)\n"
            "import numpy as np\n"
            "\n"
            "inst = toy_instance('toy_B_3x4', N=3, T=4)\n"
            "print(f\"Instance: {inst.name}\")\n"
            "print(f\"  n_vars = {inst.n_vars}\")\n"
            "print(f\"  P_target = {inst.P_target_kW} kW\")\n"
